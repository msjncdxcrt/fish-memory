export const DEFAULT_TASK_CONTEXT = 'fact';

let taskContextKey = DEFAULT_TASK_CONTEXT;
let taskContextCustom = '';

/** 自定义正文非空时优先于选项；未知键回落到默认破限词。 */
export function setTaskContext(key, custom = taskContextCustom) {
    taskContextKey = Object.hasOwn(TASK_CONTEXT_VARIANTS, key) ? key : DEFAULT_TASK_CONTEXT;
    taskContextCustom = String(custom ?? '');
    return taskContextKey;
}

export function currentTaskContext() { return taskContextKey; }

/** 当前生效的开场白原文：自定义 > 所选选项 > 原生。 */
export function taskContextText(key = taskContextKey, custom = taskContextCustom) {
    const own = String(custom ?? '').trim();
    if (own) return own;
    const name = Object.hasOwn(TASK_CONTEXT_VARIANTS, key) ? key : DEFAULT_TASK_CONTEXT;
    return TASK_CONTEXT_VARIANTS[name] ?? TASK_CONTEXT;
}

/** 只替换以档案员段开头的任务文本；预设条目、备注等其它文本原样返回。 */
export function applyTaskContext(text) {
    const value = String(text ?? '');
    if (!value.startsWith(TASK_CONTEXT)) return value;
    const custom = taskContextCustom.trim();
    if (custom) return `${custom}\n\n${value.slice(TASK_CONTEXT.length).replace(/^\s+/, '')}`;
    if (taskContextKey === 'builtin') return value;
    return TASK_CONTEXT_VARIANTS[taskContextKey] + value.slice(TASK_CONTEXT.length);
}

